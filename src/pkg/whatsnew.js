// «Что нового»: список релизов изменений для модалки на старте.
// Каждый элемент — отдельный релиз: версия-дата (ISO YYYY-MM-DD) и список изменений.
// Новые релизы дописываются в конец массива. Пользователю показываем только те,
// чья версия выше подтверждённой им (в localStorage), и после «ОК» записываем самую
// свежую версию. Дата-версия сравнивается как строка: ISO-формат сортируется
// лексикографически, поэтому `>`/`<` дают хронологический порядок.
export const WHATS_NEW = [
  {
    version: '2026-10-19',
    changes: [
      'Добавлен выбор селективных предметов (английский, физкультура, программирование). Выбрать можно открыв у пары меню с тремя точками',
      'Улучшена работа в офлайн-режиме',
      'Темная тема стала еще темнее 😈',
      'Добавлена фоновая подгрузка данных',
      'Добавлено уведомление "Что нового"',
      'Исправлено время пар по ИИ в пн',
      'Добавлено отображение времени перерыва у текущей пары',
    ],
  },
];

// Самая свежая версия (последний добавленный релиз) — её и записываем после «ОК».
export function latestVersion(list = WHATS_NEW) {
  const last = list[list.length - 1];
  return last ? last.version : null;
}

// Изменения всех релизов, которые пользователь ещё не видел: версия выше lastSeen.
// Отсутствие lastSeen (первый заход) — значит ничего не подтверждено, показываем всё.
export function unseenChanges(list, lastSeen) {
  if (!lastSeen) return list.flatMap((entry) => entry.changes);
  return list.filter((entry) => entry.version > lastSeen).flatMap((entry) => entry.changes);
}